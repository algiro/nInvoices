    ON "VerifactuRecords" ("OwnerId", "Sequence");

CREATE OR REPLACE FUNCTION verifactu_records_append_only() RETURNS trigger AS $$
BEGIN
    RAISE EXCEPTION 'Verifactu records are append-only: a saved record cannot be changed or deleted';
END;
$$ LANGUAGE plpgsql;

DROP TRIGGER IF EXISTS verifactu_records_append_only ON "VerifactuRecords";
CREATE TRIGGER verifactu_records_append_only
    BEFORE UPDATE OR DELETE ON "VerifactuRecords"
    FOR EACH ROW EXECUTE FUNCTION verifactu_records_append_only();

