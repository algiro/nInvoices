-- regimes ask for on each tax (how a 0% VAT is treated).
-- The records are append-only. The application refuses to change or delete them; the trigger below
-- makes the database refuse too, so not even a stray SQL statement can alter the chain.
-- Idempotent: safe to run repeatedly.

\set ON_ERROR_STOP on
\connect ninvoices_db

BEGIN;

ALTER TABLE "Taxes" ADD COLUMN IF NOT EXISTS "ComplianceValues" text NOT NULL DEFAULT '{}';

CREATE TABLE IF NOT EXISTS "VerifactuRecords" (
    "Id"            bigint GENERATED BY DEFAULT AS IDENTITY,
    "Sequence"      bigint       NOT NULL,
    "Kind"          varchar(20)  NOT NULL,
    "InvoiceId"     bigint       NOT NULL,
    "IssuerTaxId"   varchar(9)   NOT NULL,
    "InvoiceNumber" varchar(60)  NOT NULL,
    "IssueDate"     varchar(10)  NOT NULL,
    "InvoiceType"   varchar(2)   NOT NULL,
    "TotalTax"      varchar(20)  NOT NULL,
    "TotalAmount"   varchar(20)  NOT NULL,
    "PreviousHash"  varchar(64)  NOT NULL,
    "GeneratedAt"   varchar(40)  NOT NULL,
    "Hash"          varchar(64)  NOT NULL,
    "Xml"           text         NOT NULL,
    "CreatedAt"     timestamp with time zone NOT NULL,
    "UpdatedAt"     timestamp with time zone NULL,
    "OwnerId"       varchar(255) NOT NULL,
    CONSTRAINT "PK_VerifactuRecords" PRIMARY KEY ("Id"),
    CONSTRAINT "FK_VerifactuRecords_Invoices_InvoiceId"
        FOREIGN KEY ("InvoiceId") REFERENCES "Invoices" ("Id") ON DELETE RESTRICT
);

